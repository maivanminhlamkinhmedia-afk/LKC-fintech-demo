import { diagnosticCase, diagnosticLocation, formatDiagnosticRecord } from '../../scripts/cms-e2e/diagnostics.mjs'

export default class SafeReporter {
  constructor({ write = line => process.stdout.write(line) } = {}) { this.write = write }

  emit(kind, record) {
    const line = formatDiagnosticRecord(kind, record)
    if (line) this.write(`${line}\n`)
  }

  onBegin(_config, suite) { this.emit('DISCOVERY', { count: suite.allTests().length }) }

  onStepEnd(test, _result, step) {
    const definition = diagnosticCase(test)
    let controlled = step
    // Only explicit test.step codes or failed expect leaves carry diagnostics.
    // Do not read autogenerated API/assertion titles, params or titlePath().
    if (step.category === 'expect' && step.error) {
      const seen = new Set()
      controlled = step.parent
      while (controlled && seen.size < 64 && !seen.has(controlled)) {
        if (controlled.category === 'test.step' && definition.steps.includes(controlled.title)) break
        seen.add(controlled)
        controlled = controlled.parent
      }
      if (!controlled || seen.has(controlled) || seen.size >= 64) return
    } else if (step.category !== 'test.step') return
    if (!definition.steps.includes(controlled.title)) return

    let assertionLocation = null, assertionSource = null
    if (step.category === 'expect') {
      // Distinct structured API fields: never parse stacks or infer an assertion
      // line from the enclosing test/controlled step declaration.
      assertionLocation = diagnosticLocation(step.error?.location, definition.file)
      if (assertionLocation) assertionSource = 'error.location'
      else {
        assertionLocation = diagnosticLocation(step.location, definition.file)
        if (assertionLocation) assertionSource = 'step.location'
      }
    }
    this.emit('DIAGNOSTIC', {
      caseId: definition.caseId, stepCode: controlled.title, status: step.error ? 'failed' : 'passed',
      testLocation: diagnosticLocation(test.location, definition.file),
      stepLocation: diagnosticLocation(controlled.location, definition.file),
      assertionLocation, assertionSource,
    })
  }

  onTestEnd(test, result) {
    const definition = diagnosticCase(test)
    this.emit('CASE', { caseId: definition.caseId,
      status: ['passed', 'failed', 'timedOut', 'skipped', 'interrupted'].includes(result.status) ? result.status : 'unknown',
      testLocation: diagnosticLocation(test.location, definition.file) })
  }

  onStdOut() { /* Never forward test-owned output, including forged protocol lines. */ }
  onStdErr() { /* Never forward browser/app diagnostics or credential-bearing call logs. */ }
  onError() { this.emit('RESULT', { status: 'infrastructure-error-details-redacted' }) }
  onEnd(result) {
    this.emit('RESULT', { status: ['passed', 'failed', 'timedout', 'interrupted'].includes(result.status) ? result.status : 'unknown' })
    // No status return value: Playwright retains its original suite verdict.
  }
}
