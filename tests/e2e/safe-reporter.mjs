import { diagnosticCase, diagnosticLocation, formatDiagnosticRecord, MEDIA_TIMING_BODIES } from '../../scripts/cms-e2e/diagnostics.mjs'
import { TAX_TIMING_BODIES, TAX_TIMING_HOOKS } from '../../scripts/cms-e2e/taxonomy-diagnostics.mjs'

function enclosingPhase(step, definition) {
  const seen = new Set()
  let current = step
  while (current && seen.size < 64 && !seen.has(current)) {
    if (current.category === 'test.step' && definition.steps.includes(current.title)) return current
    seen.add(current); current = current.parent
  }
  return null
}

export default class SafeReporter {
  constructor({ write = line => process.stdout.write(line) } = {}) { this.write = write; this.bodies = new WeakMap() }

  emit(kind, record) {
    const line = formatDiagnosticRecord(kind, record)
    if (line) this.write(`${line}\n`)
  }

  onBegin(_config, suite) { this.emit('DISCOVERY', { count: suite.allTests().length }) }

  timing(test, result, step, ended) {
    const definition = diagnosticCase(test), bodyCode = TAX_TIMING_BODIES[definition.caseId] ?? MEDIA_TIMING_BODIES[definition.caseId]
    if (!bodyCode) return
    let scope, phaseCode
    if (step.category === 'hook' && Object.hasOwn(TAX_TIMING_HOOKS, step.title)) {
      scope = 'hook'; phaseCode = TAX_TIMING_HOOKS[step.title]
    } else if (step.category === 'fixture') { scope = 'fixture'; phaseCode = 'PW_FIXTURE' }
    else if (step.category === 'test.step' && definition.steps.includes(step.title)) { scope = 'phase'; phaseCode = step.title }
    else if (step.category === 'expect') {
      const phase = enclosingPhase(step.parent, definition)
      if (!phase) return
      scope = 'assertion'; phaseCode = phase.title
    } else return
    // Prefer the worker's public structured times/duration. No browser clock or
    // raw API titles/params/errors are read. Missing or invalid metadata drops
    // only TIMING; existing DIAGNOSTIC/CASE verdict reporting is unchanged.
    if (!(step.startTime instanceof Date) || !(result.startTime instanceof Date)) return
    const start = step.startTime.getTime(), duration = ended ? step.duration : 0
    if (!Number.isFinite(start) || !Number.isFinite(duration) || duration < 0) return
    if (scope === 'phase' && phaseCode === bodyCode) {
      this.bodies.set(result, { start, ended, duration })
    }
    const body = this.bodies.get(result)
    this.emit('TIMING', {
      caseId: definition.caseId, phaseCode, scope, status: ended ? step.error ? 'failed' : 'passed' : 'started',
      durationMs: Math.round(duration), testOffsetMs: Math.round(start - result.startTime.getTime()),
      bodyState: !body ? 'notStarted' : body.ended ? 'ended' : 'running',
      bodyElapsedMs: !body ? 0 : Math.round(body.ended ? body.duration : start + duration - body.start),
      testTimeoutMs: test.timeout, location: diagnosticLocation(step.location, definition.file),
    })
  }

  onStepBegin(test, result, step) { this.timing(test, result, step, false) }

  onStepEnd(test, _result, step) {
    this.timing(test, _result, step, true)
    const definition = diagnosticCase(test)
    let controlled = step
    // Only explicit test.step codes or failed expect leaves carry diagnostics.
    // Do not read autogenerated API/assertion titles, params or titlePath().
    if (step.category === 'expect' && step.error) {
      const seen = new Set()
      controlled = step.parent
      while (controlled && seen.size < 64 && !seen.has(controlled)) {
        if (controlled.category === 'test.step' && definition.steps.includes(controlled.title)) break
        seen.add(controlled)
        controlled = controlled.parent
      }
      if (!controlled || seen.has(controlled) || seen.size >= 64) return
    } else if (step.category !== 'test.step') return
    if (!definition.steps.includes(controlled.title)) return

    let assertionLocation = null, assertionSource = null
    if (step.category === 'expect') {
      // Distinct structured API fields: never parse stacks or infer an assertion
      // line from the enclosing test/controlled step declaration.
      assertionLocation = diagnosticLocation(step.error?.location, definition.file)
      if (assertionLocation) assertionSource = 'error.location'
      else {
        assertionLocation = diagnosticLocation(step.location, definition.file)
        if (assertionLocation) assertionSource = 'step.location'
      }
    }
    this.emit('DIAGNOSTIC', {
      caseId: definition.caseId, stepCode: controlled.title, status: step.error ? 'failed' : 'passed',
      testLocation: diagnosticLocation(test.location, definition.file),
      stepLocation: diagnosticLocation(controlled.location, definition.file),
      assertionLocation, assertionSource,
    })
  }

  onTestEnd(test, result) {
    const definition = diagnosticCase(test)
    if (Object.hasOwn(MEDIA_TIMING_BODIES, definition.caseId)) {
      for (const annotation of result.annotations ?? []) {
        if (annotation.type !== 'cms-media-observation' || typeof annotation.description !== 'string'
          || annotation.description.length > 512) continue
        try {
          const observation = JSON.parse(annotation.description)
          if (!observation || typeof observation !== 'object' || Object.hasOwn(observation, 'caseId')) continue
          this.emit('MEDIA_OBSERVATION', { ...observation, caseId: definition.caseId })
        }
        catch { /* Untrusted diagnostics never alter the test verdict. */ }
      }
    }
    this.emit('CASE', { caseId: definition.caseId,
      status: ['passed', 'failed', 'timedOut', 'skipped', 'interrupted'].includes(result.status) ? result.status : 'unknown',
      testLocation: diagnosticLocation(test.location, definition.file) })
  }

  onStdOut() { /* Never forward test-owned output, including forged protocol lines. */ }
  onStdErr() { /* Never forward browser/app diagnostics or credential-bearing call logs. */ }
  onError() { this.emit('RESULT', { status: 'infrastructure-error-details-redacted' }) }
  onEnd(result) {
    this.emit('RESULT', { status: ['passed', 'failed', 'timedout', 'interrupted'].includes(result.status) ? result.status : 'unknown' })
    // No status return value: Playwright retains its original suite verdict.
  }
}
